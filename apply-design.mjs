import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const kit=path.dirname(fileURLToPath(import.meta.url));
const rootArg=process.argv.indexOf('--root');
if(rootArg<0||!process.argv[rootArg+1])throw Error('Gebruik: node apply-design.mjs --root /pad/naar/bestaande/publieke/webmap');
const target=fs.realpathSync(path.resolve(process.argv[rootArg+1]));
const index=path.join(target,'index.html');
const before=fs.readFileSync(index,'utf8');
if(!before.includes('id="root"')||!before.includes('/assets/index-ChlEB3UH.js'))throw Error('Dit is niet de gecontroleerde Amsterdam-publicatie. Controleer de huidige app en de compatibiliteit vóór installatie.');
const suffix='?v=20261019';
const assets=['amsterdam-heerlen.css','amsterdam-regulations.css','amsterdam-regulations-data.js','amsterdam-heerlen.js','amsterdam-regulations.js'];
const tags='\n    <!-- Amsterdam presentation and adopted Heerlen regulations. Original app/backend retained. -->\n'+assets.map(file=>file.endsWith('.css')?'    <link rel="stylesheet" href="/assets/'+file+suffix+'">':'    <script defer src="/assets/'+file+suffix+'"></script>').join('\n')+'\n';
const clean=before.replace(/\s*<!-- Amsterdam (?:design:|presentation and)[\s\S]*?-->/g,'').replace(/\s*<(?:link[^>]*href|script[^>]*src)="\/assets\/amsterdam-(?:heerlen|regulations)[^"]*"[^>]*>(?:<\/script>)?/g,'');
const after=clean.replace(/\s*<\/head>/,tags+'  </head>');
if(after===before&&!before.includes('/assets/amsterdam-heerlen.css'))throw Error('Geen head-element gevonden.');
const backup=index+'.before-heerlen-design';
if(!fs.existsSync(backup))fs.copyFileSync(index,backup,fs.constants.COPYFILE_EXCL);
fs.mkdirSync(path.join(target,'assets'),{recursive:true});
for(const file of assets)fs.copyFileSync(path.join(kit,'assets',file),path.join(target,'assets',file));
fs.writeFileSync(index,after);
console.log(JSON.stringify({webroot:target,backup,originalSha256:createHash('sha256').update(before).digest('hex'),changedFiles:['index.html',...assets.map(f=>'assets/'+f)],backendChanged:false,reactBundleChanged:false},null,2));
